  @override
  void initState() {
    super.initState();
    _messageController = TextEditingController();
    _messageStream = _buildMessageStream();
    _loadParticipants();
    _bookingContextFuture = widget.isCustomerService
        ? Future<Map<String, dynamic>?>.value(null)
        : ChatService().getConversationBookingContext(widget.conversationId);
    _bookingContextFuture.then((booking) {
      if (!mounted) return;
      final status = booking?['status']?.toString().trim().toLowerCase();
      if (status != null) setState(() => _bookingStatus = status);
    });
    _loadRestrictionState();
    _messageController.addListener(_handleTypingChanged);
    _setupTypingChannel();
    if (widget.isCustomerService) {
      unawaited(_loadConfiguredSupportFaqs());
    } else {
      unawaited(_markCurrentMessagesRead());
    }
  }

  Future<void> _loadConfiguredSupportFaqs() async {
    final faqs = await SupportFaqService().getFaqs(_normalizedRole);
    if (!mounted) return;
    setState(() {
      _configuredSupportFaqs = faqs
          .map((faq) => _SupportFaq(question: faq.question, answer: faq.answer))
          .toList();
    });
  }

  void _loadParticipants() {
    _participantsFuture = ChatService().getConversationParticipants(
      widget.conversationId,
    );
  }

  Stream<List<Map<String, dynamic>>> _buildMessageStream() {
    return ChatService().subscribeToMessages(widget.conversationId).map((
      messages,
    ) {
      final currentUserId = _authService.currentUser?.id;
      final hasUnreadIncoming =
          currentUserId != null &&
          messages.any(
            (message) =>
                message['sender_id']?.toString() != currentUserId &&
                message['is_read'] != true,
          );
      if (hasUnreadIncoming) {
        _markReadDebounce?.cancel();
        _markReadDebounce = Timer(
          const Duration(milliseconds: 250),
          () => unawaited(_markCurrentMessagesRead()),
        );
      }
      final serverIds = messages
          .map((message) => message['id']?.toString())
          .whereType<String>()
          .toSet();
      _pendingMessages.removeWhere(
        (message) => serverIds.contains(message['id']?.toString()),
      );
      return messages;
    });
  }

  void _setupTypingChannel() {
    final currentUserId = _authService.currentUser?.id;
    _typingChannel = Supabase.instance.client
        .channel(ChatService().typingChannelName(widget.conversationId))
        .onBroadcast(
          event: 'typing',
          callback: (rawPayload) {
            final nested = rawPayload['payload'];
            final payload = nested is Map
                ? Map<String, dynamic>.from(nested)
                : rawPayload;
            final userId = payload['user_id']?.toString();
            if (userId == null || userId.isEmpty || userId == currentUserId) {
              return;
            }
            final isTyping = payload['is_typing'] == true;
            _typingExpiryTimers.remove(userId)?.cancel();
            if (!mounted) return;
            setState(() {
              if (isTyping) {
                _typingUsers[userId] =
                    payload['name']?.toString().trim().isNotEmpty == true
                    ? payload['name'].toString().trim()
                    : 'Someone';
              } else {
                _typingUsers.remove(userId);
              }
            });
            if (isTyping) {
              _typingExpiryTimers[userId] = Timer(
                const Duration(seconds: 3),
                () {
                  if (!mounted) return;
                  setState(() => _typingUsers.remove(userId));
                },
              );
            }
          },
        )
        .subscribe();
  }

  void _handleTypingChanged() {
    final isTyping = _messageController.text.trim().isNotEmpty;
    unawaited(_sendTypingState(isTyping));
    _typingStopTimer?.cancel();
    if (isTyping) {
      _typingStopTimer = Timer(
        const Duration(milliseconds: 1200),
        () => unawaited(_sendTypingState(false)),
      );
    }
  }

  Future<void> _sendTypingState(bool isTyping) async {
    final user = _authService.currentUser;
    final channel = _typingChannel;
    if (user == null || channel == null) return;
    final metadataName = user.userMetadata?['full_name']?.toString().trim();
    final displayName = widget.isCustomerService && widget.userRole == 'admin'
        ? 'Admin support'
        : metadataName?.isNotEmpty == true
        ? metadataName!
        : widget.isCustomerService
        ? 'User'
        : 'Someone';
    try {
      await channel.sendBroadcastMessage(
        event: 'typing',
        payload: {
          'user_id': user.id,
          'name': displayName,
          'is_typing': isTyping,
        },
      );
    } catch (e) {
      debugPrint('Typing status skipped: $e');
    }
  }

  String get _typingLabel {
    final names = _typingUsers.values.toSet().toList();
    if (names.isEmpty) return '';
    if (names.length == 1) return '${names.first} is typing...';
    return '${names.take(2).join(' and ')} are typing...';
  }

  Future<void> _markCurrentMessagesRead() async {
    final userId = _authService.currentUser?.id;
    if (userId == null || widget.conversationId.trim().isEmpty) return;
    try {
      await ChatService().markMessagesAsRead(widget.conversationId, userId);
    } catch (e) {
      debugPrint('Could not mark conversation as read: $e');
    }
  }

  Future<void> _loadRestrictionState() async {
    final state = await _restrictionService.getCurrentUserRestriction();
    if (!mounted) return;
    setState(() {
      _restrictionState = state;
    });
    _restartRestrictionTicker();
  }

  void _restartRestrictionTicker() {
    _restrictionTicker?.cancel();
    if (!_isMessagingRestricted) return;

    _restrictionTicker = Timer.periodic(const Duration(seconds: 1), (_) {
      if (!mounted) return;
      setState(() {});
      if (!_isMessagingRestricted) {
        _restrictionTicker?.cancel();
      }
    });
  }

  Future<void> _sendMessage() async {
    if (_messageController.text.trim().isEmpty) return;
    if (_isMessagingRestricted) {
      setState(() {
        _warningMessage =
            'Messaging is temporarily restricted. Please wait for the timer to expire before sending another message.';
      });
      return;
    }

    final messageContent = _messageController.text.trim();
    final currentUser = _authService.currentUser;

    if (currentUser == null) return;

    final optimisticId =
        'local-${DateTime.now().microsecondsSinceEpoch}-${currentUser.id}';
    setState(() {
      _isLoading = true;
      _pendingMessages.add({
        'id': optimisticId,
        'conversation_id': widget.conversationId,
        'sender_id': currentUser.id,
        'content': messageContent,
        'message': messageContent,
        'created_at': DateTime.now().toUtc().toIso8601String(),
        '_is_sending': true,
      });
    });
    _messageController.clear();
    unawaited(_sendTypingState(false));

    try {
      // Analyze message for off-platform transaction attempts
      final analysis = await MessageFilterService.analyzeMessageWithFilters(
        messageContent,
      );

      // Show warning if suspicious
      if (analysis['is_suspicious']) {
        setState(() {
          _warningMessage = analysis['risk_level'] == 'high'
              ? '⚠️ This message may contain contact details. Keep payments within the app for security.'
              : 'ℹ️ Reminder: Keep all transactions within the app for protection.';
        });
      } else {
        setState(() => _warningMessage = null);
      }

      // Send message
      final sentMessage = await ChatService().sendMessage(
        conversationId: widget.conversationId,
        senderId: currentUser.id,
        content: messageContent,
      );
      if (mounted) {
        setState(() {
          final index = _pendingMessages.indexWhere(
            (message) => message['id'] == optimisticId,
          );
          if (index >= 0) _pendingMessages[index] = sentMessage;
        });
      }

      // Flag if necessary
      if (analysis['should_flag']) {
        final messageId =
            sentMessage['id']?.toString() ??
            DateTime.now().millisecondsSinceEpoch.toString();
        await MessageFilterService.flagMessageForReview(
          messageId: messageId,
          conversationId: widget.conversationId,
          senderId: currentUser.id,
          flagReason:
              'Potential off-platform transaction attempt: ${analysis['found_keywords'].join(', ')}',
          messageContent: messageContent,
        );
        await _restrictionService.applyPolicyViolation(
          userId: currentUser.id,
          conversationId: widget.conversationId,
        );

        // Show flag notification
        if (mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            const SnackBar(
              content: Text(
                '📋 Message has been flagged for safety review. Keep transactions within the app.',
              ),
              duration: Duration(seconds: 3),
              backgroundColor: AppColors.warning,
            ),
          );
        }
      }

      await _loadRestrictionState();

      if (mounted) {
        setState(() => _isLoading = false);
      }
    } catch (e) {
      if (mounted) {
        setState(() {
          final index = _pendingMessages.indexWhere(
            (message) => message['id'] == optimisticId,
          );
          if (index >= 0) {
            _pendingMessages[index] = {
              ..._pendingMessages[index],
              '_is_sending': false,
              '_send_failed': true,
            };
          }
          _isLoading = false;
        });
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Failed to send message: $e'),
            backgroundColor: AppColors.error,
          ),
        );
      }
    }
  }

  Future<void> _pickAndSendAttachment() async {
    if (_isMessagingRestricted || _isUploadingAttachment) {
      return;
    }

    final currentUser = _authService.currentUser;
    if (currentUser == null) return;

    final result = await FilePicker.platform.pickFiles(
      type: FileType.any,
      withData: false,
    );
    final picked = result?.files.single;
    final path = picked?.path;
    if (picked == null || path == null || path.isEmpty) return;

    setState(() {
      _isUploadingAttachment = true;
      _warningMessage = null;
    });

    try {
      final file = File(path);
      final url = await ChatService().uploadChatAttachment(
        senderId: currentUser.id,
        file: file,
        fileName: picked.name,
      );
      final type = _attachmentTypeForName(picked.name);

      await ChatService().sendMessage(
        conversationId: widget.conversationId,
        senderId: currentUser.id,
        content: 'Sent an attachment: ${picked.name}',
        attachmentUrl: url,
        attachmentType: type,
        attachmentName: picked.name,
        attachmentSize: picked.size,
      );
    } catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('Failed to send attachment: $e'),
          backgroundColor: AppColors.error,
        ),
      );
    } finally {
      if (mounted) {
        setState(() {
          _isUploadingAttachment = false;
        });
      }
    }
  }

  Future<void> _confirmDeleteMessage(Map<String, dynamic> message) async {
    final messageId = message['id']?.toString();
    final userId = _authService.currentUser?.id;
    if (messageId == null || messageId.isEmpty || userId == null) return;
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (dialogContext) => AlertDialog(
        backgroundColor: AppColors.darkBgSecondary,
        title: const Text(
          'Delete message?',
          style: TextStyle(color: AppColors.textPrimary),
        ),
        content: const Text(
          'The message will remain in the conversation as "Message deleted".',
          style: TextStyle(color: AppColors.textSecondary),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(dialogContext, false),
            child: const Text('Cancel'),
          ),
          FilledButton.icon(
            onPressed: () => Navigator.pop(dialogContext, true),
            style: FilledButton.styleFrom(
              backgroundColor: AppColors.error,
              foregroundColor: Colors.white,
            ),
            icon: const Icon(Icons.delete_outline),
            label: const Text('Delete'),
          ),
        ],
      ),
    );
    if (confirmed != true) return;
    try {
      final deleted = await ChatService().softDeleteMessage(
        messageId: messageId,
        userId: userId,
      );
      if (!mounted) return;
      setState(() => _messageOverrides[messageId] = deleted);
    } catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('Could not delete message: $e'),
          backgroundColor: AppColors.error,
        ),
      );
    }
  }

  String _attachmentTypeForName(String fileName) {
    final lower = fileName.toLowerCase();
    if (lower.endsWith('.jpg') ||
        lower.endsWith('.jpeg') ||
        lower.endsWith('.png') ||
        lower.endsWith('.webp')) {
      return 'image';
    }
    if (lower.endsWith('.mp4') ||
        lower.endsWith('.mov') ||
        lower.endsWith('.avi')) {
      return 'video';
    }
    return 'document';
  }

  IconData _attachmentIcon(String type) {
    switch (type) {
      case 'image':
        return Icons.image_outlined;
      case 'video':
        return Icons.videocam_outlined;
      default:
        return Icons.insert_drive_file_outlined;
    }
  }

  String _visibleMessageContent(String content) {
    return content
        .replaceFirst(RegExp(r'\n\n\[Audit: [^\]]+\]\s*$'), '')
        .trim();
  }

  bool _isChecklistAudit(String content) {
    return content.startsWith('Before-Release Checklist Submitted') ||
        content.startsWith('After-Return Checklist Submitted');
  }

  Future<void> _openAttachmentPreview({
    required String url,
    required String type,
    required String name,
  }) async {
    final normalizedType = type.toLowerCase();
    if (normalizedType == 'image') {
      await showDialog<void>(
        context: context,
        barrierColor: Colors.black87,
        builder: (dialogContext) => Dialog.fullscreen(
          backgroundColor: Colors.black,
          child: SafeArea(
            child: Stack(
              children: [
                Positioned.fill(
                  child: InteractiveViewer(
                    minScale: 0.8,
                    maxScale: 5,
                    child: Center(
                      child: OptimizedNetworkImage(
                        imageUrl: url,
                        fit: BoxFit.contain,
                        isThumbnail: false,
                      ),
                    ),
                  ),
                ),
                Positioned(
                  top: 10,
                  right: 10,
                  child: IconButton.filled(
                    tooltip: 'Close preview',
                    onPressed: () => Navigator.pop(dialogContext),
                    icon: const Icon(Icons.close_rounded),
                  ),
                ),
              ],
            ),
          ),
        ),
      );
      return;
    }
    if (normalizedType == 'video') {
      await Navigator.of(context).push(
        MaterialPageRoute<void>(
          fullscreenDialog: true,
          builder: (_) => _VideoAttachmentViewer(url: url, title: name),
        ),
      );
      return;
    }
    await launchUrl(Uri.parse(url), mode: LaunchMode.externalApplication);
  }

