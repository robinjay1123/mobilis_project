        return const _DriverMessagesTab();
      case 3:
        return _NotificationsTab(key: _notificationsKey);
      case 4:
        return _ProfileTab(
          onThemeToggle: widget.onThemeToggle,
          isDarkMode: widget.isDarkMode,
          onLogout: _handleLogout,
